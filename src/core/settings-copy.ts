export const agentActivityLabel = (title: string): string => agentActivityLabels[title] ?? title;

export const isAgentActivityTitle = (title: string): boolean =>
  Object.keys(agentActivityLabels).some((activity) => activity.toLowerCase() === title.trim().toLowerCase())
  || Object.values(agentActivityLabels).some((activity) => activity.toLowerCase() === title.trim().toLowerCase());
